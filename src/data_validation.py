_LAST_NAME = CounselingConfig.COLUMN_MAPPING['last_name']
_FIRST_NAME = CounselingConfig.COLUMN_MAPPING['first_name']
_ACTIVITY_ID = CounselingConfig.COLUMN_MAPPING['activity_id']


def validate_counseling_date(date_str: str) -> bool:
    """
    Validates that the counseling date is not before the current fiscal-year start.

    Args:
        date_str: A date string in YYYY-MM-DD format

    Returns:
        Boolean indicating if the date is valid
    """
    if not date_str:
        return True

    try:
        date_obj = datetime.strptime(date_str, "%Y-%m-%d")
        min_date = datetime.strptime(fiscal_year_start(), "%Y-%m-%d")
        return date_obj >= min_date
    except ValueError:
        return False

# =============================================================================
# ROWS THAT ARE NOT RECORDS
# =============================================================================

# A footer line is a row with one filled cell -- in a file this wide. In a
# narrower one a single value could be a sparse record.
_FOOTER_MIN_COLUMNS = 3


def non_record_reason(row: dict[str, str]) -> str | None:
    """Why `row` is not a record at all -- it is blank, repeats the header
    row, or is a report's title or footer line -- or None.

    Two exports pasted together repeat the header row, and a report export
    carries title and footer lines -- Salesforce's adds the report name, a
    copyright line, "Confidential Information - Do Not Distribute" and
    "Generated By: ..." -- each a row with one filled cell. Both were filed as
    training events (the header row as an event called "Class/Event ID") or
    reported as clients with no Contact ID. Pass the row as the CSV has it,
    before a converter renames columns or fills in its defaults.
    """
    filled = [(column, str(value).strip()) for column, value in row.items()
              if value and str(value).strip()]
    if not filled:
        # A line of commas, or the '""' lines around a report's footer: a
        # blank line, not a record missing its ID.
        return "is blank"
    repeated = sum(1 for column, value in filled if _is_own_header(column, value))
    if repeated >= 2 and repeated * 2 >= len(filled):
        return "repeats the header row"
    if len(filled) == 1 and len(row) >= _FOOTER_MIN_COLUMNS:
        column, value = filled[0]
        return f"holds only '{value}' (in '{column}'), like a report's title or footer line"
    return None


def _is_own_header(column: str, value: str) -> bool:
    """True when a cell holds its own column's header, as normalize_header
    reads headers -- called only when normalizing could change the cell,
    since this runs on every cell of every row."""
    if value.casefold() == column.casefold():
        return True
    if value.isprintable() and "  " not in value:
        return False
    return normalize_header(value).casefold() == column.casefold()


def _skip_non_record(row: dict[str, str], row_index: int, validator: ValidationTracker) -> bool:
    """Record a warning for, and return True about, a row that isn't a
    record (see non_record_reason)."""
    why = non_record_reason(row)
    if why is None:
        return False
    validator.add_issue(f"Row_{row_index}", "warning", VC.INVALID_FORMAT, "record",
                        f"Row {row_index} {why}, so it was skipped.", event_id="")
    return True


