"""The same data, written the ways real exports write it, must convert the same.

Most conversion failures this project has fixed were one file's formatting
rather than its data: Excel's Windows-1252 or UTF-16 output, CRLF line ends,
Salesforce quoting every cell and appending a copyright and "Generated By"
footer, a header with a stray space or a zero-width character, two exports
pasted into one file, columns in another order. Each was fixed for the case
that was reported. These tests state the property those fixes share, so the
next variant fails here instead of in a user's filing:

    a transformation that does not change what a file says must not change the
    XML it converts to -- byte for byte -- nor add an error.

Each base file is a shipped sample with rows added that carry the characters
that broke conversions (accents, curly quotes, a comma and a quotation mark in
a company name, a multi-line comment). Every transformation is run through the
CLI converter (which decodes the bytes itself) and the text ones through the
worker's run_conversion (which receives text the web already decoded).
"""

