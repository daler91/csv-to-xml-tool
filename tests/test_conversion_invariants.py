# --- base files -------------------------------------------------------------


def _read_rows(text):
    return list(csv.reader(io.StringIO(text)))


def _write_rows(rows, **kwargs):
    out = io.StringIO()
    csv.writer(out, lineterminator="\n", **kwargs).writerows(rows)
    return out.getvalue()


def _sample(name):
    with open(os.path.join(_SAMPLES, name), encoding="utf-8") as f:
        return f.read()


def _with_rows(sample_text, add_columns, new_rows):
    """The sample, widened by `add_columns` (blank in its own rows), plus each
    of `new_rows`: a copy of the sample's first row with the given cells."""
    rows = _read_rows(sample_text)
    header, body = rows[0], rows[1:]
    header = header + [c for c in add_columns if c not in header]
    body = [r + [""] * (len(header) - len(r)) for r in body]
    for changes in new_rows:
        row = dict(zip(header, body[0], strict=True))
        unknown = set(changes) - set(header)
        assert not unknown, f"not a column of this file: {unknown}"
        row.update(changes)
        body.append([row[c] for c in header])
    return _write_rows([header, *body])


