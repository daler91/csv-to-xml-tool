# --- transformations --------------------------------------------------------
# Text ones take and return CSV text; byte ones return the file's bytes.


def _map_cells(text, fn, header_too=False):
    rows = _read_rows(text)
    start = 0 if header_too else 1
    return _write_rows(rows[:start] + [[fn(c) for c in r] for r in rows[start:]])


def _map_header(text, fn):
    rows = _read_rows(text)
    return _write_rows([[fn(c) for c in rows[0]], *rows[1:]])


def _reverse_columns(text):
    return _write_rows([list(reversed(r)) for r in _read_rows(text)])


def _extra_columns(text):
    rows = _read_rows(text)
    extra = [["Notes", "Owner: Full Name"]] + [
        [f'Row {i}, says "hi"\nsecond line', "Pat O’Brien"] for i in range(1, len(rows))
    ]
    return _write_rows([r + e for r, e in zip(rows, extra, strict=True)])


def _trailing_blank_columns(text):
    # What Excel writes when cells to the right of the data were ever formatted.
    return _write_rows([r + ["", "", ""] for r in _read_rows(text)])


def _blank_lines(text):
    rows = _read_rows(text)
    out = io.StringIO()
    writer = csv.writer(out, lineterminator="\n")
    for row in rows:
        writer.writerow(row)
        out.write("\n")
    return out.getvalue() + "\n\n"


def _salesforce_footer(text):
    # A Salesforce report exported as CSV ends like this.
    return text + (
        '\n"Café Owners Report"\n'
        '"Copyright (c) 2000-2025 salesforce.com, inc. All rights reserved."\n'
        '"Confidential Information - Do Not Distribute"\n'
        '"Generated By:  Pat Smith  10/14/2025 9:15 AM"\n'
        '"America’s SBDC Iowa"\n'
    )


def _two_pasted_exports(text):
    # The same report exported twice, by halves, pasted into one sheet.
    rows = _read_rows(text)
    header, body = rows[0], rows[1:]
    half = len(body) // 2
    return _write_rows([header, *body[:half], header, *body[half:]])


def _swap_yes_no_case(text):
    return _map_cells(text, lambda c: {"Yes": "YES", "No": "no"}.get(c, c))


def _pad_cells(text):
    return _map_cells(text, lambda c: f"  {c} " if c else c)


TEXT_TRANSFORMS = {
    "reserialized": lambda t: _write_rows(_read_rows(t)),
    "crlf": lambda t: t.replace("\n", "\r\n"),
    "bare-cr": lambda t: t.replace("\n", "\r"),
    "no-final-newline": lambda t: t.rstrip("\n"),
    "every-cell-quoted": lambda t: _write_rows(_read_rows(t), quoting=csv.QUOTE_ALL),
    "columns-reversed": _reverse_columns,
    "unknown-columns-added": _extra_columns,
    "trailing-blank-columns": _trailing_blank_columns,
    "blank-lines-between-rows": _blank_lines,
    "salesforce-report-footer": _salesforce_footer,
    "two-pasted-exports": _two_pasted_exports,
    "header-spacing": lambda t: _map_header(t, lambda h: f" {h.replace(' ', '  ')}  "),
    "header-zero-width-chars": lambda t: _map_header(t, lambda h: f"\u200b{h}\ufeff"),
    "yes-no-in-other-case": _swap_yes_no_case,
    "cells-padded-with-spaces": _pad_cells,
}

BYTE_TRANSFORMS = {
    "utf-8-bom": lambda t: codecs.BOM_UTF8 + t.encode("utf-8"),
    "utf-16-le": lambda t: codecs.BOM_UTF16_LE + t.encode("utf-16-le"),
    "utf-16-be": lambda t: codecs.BOM_UTF16_BE + t.encode("utf-16-be"),
    "windows-1252": lambda t: t.encode("cp1252"),
    "windows-1252-crlf": lambda t: t.replace("\n", "\r\n").encode("cp1252"),
    "utf-16-le-crlf": lambda t: codecs.BOM_UTF16_LE + t.replace("\n", "\r\n").encode("utf-16-le"),
}


# --- conversion --------------------------------------------------------------


def _convert_bytes(converter_type, data):
    """Convert a file through the CLI converter; (XML bytes, tracker)."""
    converter_cls, xsd, _ = BASES[converter_type]
    with tempfile.TemporaryDirectory() as tmp:
        csv_path = os.path.join(tmp, "input.csv")
        xml_path = os.path.join(tmp, "output.xml")
        with open(csv_path, "wb") as f:
            f.write(data)
        tracker = ValidationTracker()
        logger = ConversionLogger(f"metamorphic_{converter_type}", log_to_file=False).logger
        converter_cls(logger, tracker).convert(csv_path, xml_path)
        result = validate_against_xsd(xml_path, xsd)
        assert result["is_valid"], result["errors"][:5]
        with open(xml_path, "rb") as f:
            return f.read(), tracker


def _errors(tracker):
    return sorted((i["category"], i["field_name"]) for i in tracker.issues if i["severity"] == "error")


_baselines = {}


def _baseline(converter_type):
    if converter_type not in _baselines:
        text = BASES[converter_type][2]()
        xml, tracker = _convert_bytes(converter_type, text.encode("utf-8"))
        _baselines[converter_type] = (text, xml, tracker)
    return _baselines[converter_type]


def _expected_records(converter_type, text):
    rows = _read_rows(text)
    if converter_type == "training":  # one record per event
        column = rows[0].index("Class/Event ID")
        return len({row[column] for row in rows[1:]})
    return len(rows) - 1


@pytest.mark.parametrize("converter_type", BASES)
def test_each_base_files_every_record_and_its_hard_characters(converter_type):
    """Otherwise the comparisons below could pass on a file that converts to
    nothing, or one that drops the values they are about. (The samples carry
    report errors of their own, such as a missing Legal Entity; those are
    allowed, but must be the same for every variant.)"""
    text, xml, tracker = _baseline(converter_type)
    records = _expected_records(converter_type, text)
    assert (tracker.total_records, tracker.successful_records) == (records, records)
    for marker in FILED_MARKERS[converter_type]:
        assert marker in xml.decode("utf-8")


@pytest.mark.parametrize("transform", TEXT_TRANSFORMS)
@pytest.mark.parametrize("converter_type", BASES)
def test_text_variants_convert_identically(converter_type, transform):
    text, expected_xml, expected_tracker = _baseline(converter_type)
    xml, tracker = _convert_bytes(converter_type, TEXT_TRANSFORMS[transform](text).encode("utf-8"))
    assert xml.decode("utf-8") == expected_xml.decode("utf-8")
    assert _errors(tracker) == _errors(expected_tracker)


@pytest.mark.parametrize("transform", BYTE_TRANSFORMS)
@pytest.mark.parametrize("converter_type", BASES)
def test_encoding_variants_convert_identically(converter_type, transform):
    text, expected_xml, expected_tracker = _baseline(converter_type)
    xml, tracker = _convert_bytes(converter_type, BYTE_TRANSFORMS[transform](text))
    assert xml.decode("utf-8") == expected_xml.decode("utf-8")
    assert _errors(tracker) == _errors(expected_tracker)


# --- the worker -------------------------------------------------------------
# The web app converts through run_conversion, with text it has already
# decoded, and optionally with the column mapping the user chose.


def _convert_in_worker(converter_type, text, column_mapping=None):
    """Convert text as the worker's /convert route stages it; (XML bytes, result)."""
    with tempfile.TemporaryDirectory() as tmp:
        csv_path = os.path.join(tmp, "input.csv")
        xml_path = os.path.join(tmp, "output.xml")
        with open(csv_path, "w", encoding="utf-8", newline="") as f:
            f.write(text)
        result = run_conversion(csv_path, xml_path, converter_type, column_mapping)
        assert result["xsd_valid"], result["xsd_errors"][:5]
        with open(xml_path, "rb") as f:
            return f.read(), result


def _worker_errors(result):
    return sorted((i["category"], i["field_name"]) for i in result["issues"] if i["severity"] == "error")


@pytest.mark.parametrize("transform", TEXT_TRANSFORMS)
@pytest.mark.parametrize("converter_type", BASES)
def test_the_worker_files_text_variants_as_the_cli_files_the_base(converter_type, transform):
    """The web and the command line must file the same XML for the same data."""
    text, expected_xml, _ = _baseline(converter_type)
    _, worker_base = _convert_in_worker(converter_type, text)
    xml, result = _convert_in_worker(converter_type, TEXT_TRANSFORMS[transform](text))
    assert xml.decode("utf-8") == expected_xml.decode("utf-8")
    assert _worker_errors(result) == _worker_errors(worker_base)


@pytest.mark.parametrize("converter_type", BASES)
def test_a_column_mapping_back_to_the_expected_names_converts_identically(converter_type):
    """Every column the converter reads renamed (with stray spaces, as exports
    leave them), and a mapping keyed the way the mapping page keys it -- by the
    preview's normalized header -- naming them back."""
    text, expected_xml, _ = _baseline(converter_type)
    expected_columns = set(get_expected_columns(converter_type))
    header, *body = _read_rows(text)
    renamed = [f"  Our {name} " if name in expected_columns else name for name in header]
    mapping = {normalize_header(new): old for new, old in zip(renamed, header, strict=True) if new != old}
    assert len(mapping) >= 10

    xml, result = _convert_in_worker(converter_type, _write_rows([renamed, *body]), mapping)
    assert xml.decode("utf-8") == expected_xml.decode("utf-8")
    assert not [i for i in result["issues"] if "nothing was renamed" in i["message"]]


# --- a bad row costs only its own record -------------------------------------
# A row the converter can't make sense of used to fail the whole job (a
# TypeError in the per-row error handler), and rows that are not records at
# all were filed as clients and events. Whatever one row holds, the records of
# every other row must come out exactly as they do without it, and the row
# itself must be filed or reported -- never dropped in silence.

# Identity cells of the inserted row, so its record (if filed) can be told apart.
BAD_IDENTITY = {
    "counseling": {"Contact ID": "003BADROW0000001"},
    "training-client": {"Contact ID": "003BADROW0000001", "Class/Event ID": "EVT-BAD"},
    "training": {"Class/Event ID": "701BAD001"},
}
RECORD_KEY_COLUMN = {
    "counseling": "Contact ID",
    "training-client": "Contact ID",
    "training": "Class/Event ID",
}
RECORD_KEY = {
    "counseling": "PartnerClientNumber",
    "training-client": "PartnerClientNumber",
    "training": "PartnerTrainingNumber",
}

JUNK = [
    "", " ", "N/A", "none", "Yes", "NO", "true", "0", "-1", "12.5", "Other", "Unknown",
    "Prefer not to say", "<b>&amp;\"'</b>", "line1\nline2", "x" * 300, "A; B; C", ";",
    "1E+400", "02/30/2025", "9999-12-31", "(1,500)", "\U0001F600", "=HYPERLINK(\"x\")",
]


def _junk_cells(header, _first):
    return [JUNK[i % len(JUNK)] for i in range(len(header))]


def _excel_error_cells(header, _first):
    return [("#N/A", "#REF!", "#VALUE!", "#DIV/0!")[i % 4] for i in range(len(header))]


def _invisible_cells(header, _first):
    # Every cell, the IDs included: a row that names nobody.
    return ["\u200b\u200e" for _ in header]


def _control_character_cells(header, first):
    return [f"{value}\x01\x0b\x1f" if value else "\x07" for value in first]


def _huge_cells(header, _first):
    return ["x" * 5000 for _ in header]


def _only_identity_cells(header, _first):
    return [""] * len(header)


def _unquoted_commas_row(header, first):
    # Its first value runs into the next columns: more cells than the header.
    return first + ["Smith", " Jr.", "extra", "values"]


BAD_ROWS = {
    "junk-in-every-cell": _junk_cells,
    "excel-errors": _excel_error_cells,
    "only-invisible-characters": _invisible_cells,
    "xml-illegal-control-characters": _control_character_cells,
    "5000-character-cells": _huge_cells,
    "nothing-but-its-ids": _only_identity_cells,
    "more-cells-than-the-header": _unquoted_commas_row,
}


def _records(xml):
    root = ET_SAFE.fromstring(xml)
    return list(root)


def _serialized(record):
    # Without the tail: the indentation after a record differs for the last one.
    return ET_SAFE.tostring(record).rstrip()


def _key(record, converter_type):
    element = record.find(RECORD_KEY[converter_type])
    return element.text if element is not None else None


def _with_bad_row(converter_type, text, make_cells):
    header, *body = _read_rows(text)
    cells = make_cells(header, body[0])
    if make_cells is not _invisible_cells:
        for column, value in BAD_IDENTITY[converter_type].items():
            cells[header.index(column)] = value
    return _write_rows([header, body[0], cells, *body[1:]])


@pytest.mark.parametrize("bad_row", BAD_ROWS)
@pytest.mark.parametrize("converter_type", BASES)
def test_a_bad_row_changes_no_other_record(converter_type, bad_row):
    """Inserted as data row 2, so a converter that carries one row's state into
    the next shows it too. Rows that name nobody, or hold a single value, are
    skipped as blank lines and report furniture, with a warning; that counts as
    reported."""
    text, expected_xml, expected_tracker = _baseline(converter_type)
    xml, tracker = _convert_bytes(
        converter_type, _with_bad_row(converter_type, text, BAD_ROWS[bad_row]).encode("utf-8")
    )

    bad_key = BAD_IDENTITY[converter_type][RECORD_KEY_COLUMN[converter_type]]
    others = [_serialized(r) for r in _records(xml) if _key(r, converter_type) != bad_key]
    assert others == [_serialized(r) for r in _records(expected_xml)]

    filed = any(_key(r, converter_type) == bad_key for r in _records(xml))
    known = [i["message"] for i in expected_tracker.issues]
    reported = [
        i for i in tracker.issues
        if i["message"] not in known
        and (i["record_id"] in (bad_key, "Row_2") or "Row 2" in i["message"] or "row 2" in i["message"])
    ]
    assert filed or reported, "the bad row was neither filed nor reported"
